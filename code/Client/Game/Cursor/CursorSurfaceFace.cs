/// <summary>
/// Client-side logical face resolved from a physical cursor surface hit.
/// </summary>
public enum CursorSurfaceFace
{
    /// <summary>
    /// Positive vertical face.
    /// </summary>
    Top,

    /// <summary>
    /// Negative vertical face.
    /// </summary>
    Bottom,

    /// <summary>
    /// Negative Z face.
    /// </summary>
    North,

    /// <summary>
    /// Positive Z face.
    /// </summary>
    South,

    /// <summary>
    /// Positive X face.
    /// </summary>
    East,

    /// <summary>
    /// Negative X face.
    /// </summary>
    West
}
